const TOTAL = POOLS.reduce((a, [w]) => a + w, 0);

export function randomText(rng) {
  const n = Math.floor(rng() * 41);
  const out = [];
  for (let i = 0; i < n; i++) {
    let r = rng() * TOTAL;
    let pool = POOLS[0][1];
    for (const [w, p] of POOLS) {
      if (r < w) { pool = p; break; }
      r -= w;
    }
    out.push(pool[Math.floor(rng() * pool.length)]);
  }
  return String.fromCodePoint(...out);
}
