// Generates the data modules of the JavaScript port from the files the Python package ships, so both
// implementations read the same policies and the same pinned Unicode tables:
//
//   ../src/arabic_normalize/tables/ucd_tables.json  -> src/generated/ucd-data.js  (compact, names omitted)
//   ../src/arabic_normalize/policies/*.json         -> policies/*.json (byte-identical copies)
//                                                      src/generated/policies.js (embedded for browsers)
//   ../src/arabic_normalize/_version.py             -> src/generated/version.js
//   ../LICENSE, ../LICENSE-data, ../NOTICE, ../NOTICE-unicode.txt -> copies next to package.json
//
// Usage: node scripts/build.mjs          (write)
//        node scripts/build.mjs --check  (exit 1 if any generated file is out of date)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const JS = dirname(dirname(fileURLToPath(import.meta.url)));
const ROOT = dirname(JS);
const PKG = join(ROOT, 'src', 'arabic_normalize');
const CHECK = process.argv.includes('--check');

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const outputs = [];
const emit = (path, content) => outputs.push([path, Buffer.isBuffer(content) ? content : Buffer.from(content, 'utf8')]);

// --- Unicode tables ---------------------------------------------------------------------------------
const tablesPath = join(PKG, 'tables', 'ucd_tables.json');
const tablesBytes = readFileSync(tablesPath);
const T = JSON.parse(tablesBytes.toString('utf8'));

function encRanges(ranges) {
  const out = [];
  let cur = 0;
  for (const [lo, hi] of [...ranges].sort((a, b) => a[0] - b[0])) {
    out.push(lo - cur, hi - lo);
    cur = hi;
  }
  return out;
}
function encSorted(list) {
  const out = [];
  let cur = 0;
  for (const c of [...list].sort((a, b) => a - b)) {
    out.push(c - cur);
    cur = c;
  }
  return out;
}
function encPairs(pairs, relative) { // [[cp, v]] -> [dcp, v or v-cp]
  const out = [];
  let cur = 0;
  for (const [cp, v] of [...pairs].sort((a, b) => a[0] - b[0])) {
    out.push(cp - cur, relative ? v - cp : v);
    cur = cp;
  }
  return out;
}
function encDecomp(rows) { // [[cp, d1, d2, ...]] -> [dcp, len, d1, d2, ...]
  const out = [];
  let cur = 0;
  for (const r of [...rows].sort((a, b) => a[0] - b[0])) {
    out.push(r[0] - cur, r.length - 1, ...r.slice(1));
    cur = r[0];
  }
  return out;
}
const GC_CATS = [...new Set(T.gc_ranges.map((r) => r[2]))].sort();
function encGc(rows) {
  const out = [];
  let cur = 0;
  for (const [lo, hi, cat] of [...rows].sort((a, b) => a[0] - b[0])) {
    out.push(lo - cur, hi - lo, GC_CATS.indexOf(cat));
    cur = hi;
  }
  return out;
}

const RANGE_KEYS = ['bidi_control', 'emoji_modifier', 'extended_pictographic', 'nfc_qc_maybe', 'nfc_qc_no',
  'nfkc_qc_maybe', 'nfkc_qc_no', 'noncharacter', 'script_arabic', 'script_latin', 'white_space'];
const compact = {
  format: 'arabic-normalize-js-ucd-1',
  unicode_version: T.unicode_version,
  source: T.source,
  source_sha256: T.source_sha256,
  license: T.license,
  ranges: Object.fromEntries(RANGE_KEYS.map((k) => [k, encRanges(T[k])])),
  joining_type: Object.fromEntries(Object.keys(T.joining_type).sort().map((k) => [k, encRanges(T.joining_type[k])])),
  gc_cats: GC_CATS,
  gc_ranges: encGc(T.gc_ranges),
  ccc: encPairs(T.ccc, false),
  latin_lower: encPairs(T.latin_lower, true),
  compat_decomposable: encSorted(T.compat_decomposable),
  nfd: encDecomp(T.nfd),
  nfkd: encDecomp(T.nfkd),
  compose: T.compose.flat(),
};
emit(join(JS, 'src', 'generated', 'ucd-data.js'),
  '// Generated by scripts/build.mjs from src/arabic_normalize/tables/ucd_tables.json. Do not edit.\n'
  + `// Source table sha256: ${sha256(tablesBytes)}\n`
  + `// Unicode Character Database ${T.unicode_version}. Licence: Unicode License V3 (see NOTICE-unicode.txt).\n`
  + '// Character names are omitted; everything else is the same data the Python package uses.\n'
  + `export const TABLES_SOURCE_SHA256 = ${JSON.stringify(sha256(tablesBytes))};\n`
  + `export default JSON.parse(${JSON.stringify(JSON.stringify(compact))});\n`);

// --- Policies ---------------------------------------------------------------------------------------
const policyDir = join(PKG, 'policies');
const policyFiles = readdirSync(policyDir).filter((f) => f.endsWith('.json')).sort();
const builtins = {};
const fileHashes = {};
for (const f of policyFiles) {
  const bytes = readFileSync(join(policyDir, f));
  emit(join(JS, 'policies', f), bytes);
  if (f === 'schema.json') continue;
  const id = f.slice(0, -5);
  builtins[id] = JSON.parse(bytes.toString('utf8'));
  fileHashes[id] = sha256(bytes);
}
emit(join(JS, 'src', 'generated', 'policies.js'),
  '// Generated by scripts/build.mjs from src/arabic_normalize/policies/*.json. Do not edit.\n'
  + '// Policy files: CC BY 4.0, Bayanat Labs (see LICENSE-data).\n'
  + `export const POLICY_FILE_SHA256 = Object.freeze(${JSON.stringify(fileHashes, null, 2)});\n`
  + `export const BUILTIN_POLICIES = JSON.parse(${JSON.stringify(JSON.stringify(builtins))});\n`);

// --- Version ----------------------------------------------------------------------------------------
const versionPy = readFileSync(join(PKG, '_version.py'), 'utf8');
const m = versionPy.match(/__version__\s*=\s*"([^"]+)"/);
if (!m) throw new Error('cannot read __version__ from _version.py');
emit(join(JS, 'src', 'generated', 'version.js'),
  '// Generated by scripts/build.mjs from src/arabic_normalize/_version.py. Do not edit.\n'
  + `export const LIB_VERSION = ${JSON.stringify(m[1])};\n`);

// --- Licence files ----------------------------------------------------------------------------------
for (const f of ['LICENSE', 'LICENSE-data', 'NOTICE', 'NOTICE-unicode.txt']) {
  emit(join(JS, f), readFileSync(join(ROOT, f)));
}

// --- Write or check ---------------------------------------------------------------------------------
let stale = 0;
for (const [path, content] of outputs) {
  const same = existsSync(path) && readFileSync(path).equals(content);
  if (CHECK) {
    if (!same) {
      console.error(`out of date: ${path.slice(JS.length + 1)}`);
      stale += 1;
    }
  } else if (!same) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path.slice(JS.length + 1)} (${content.length} bytes)`);
  }
}
if (CHECK) {
  if (stale) process.exit(1);
  console.log(`${outputs.length} generated files are up to date`);
}
