"""Write docs/stress/*.md and *.json from the JSON of scripts/stress/stress_run.py (numbers only).

Wikipedia (docs/stress/report.md and stats.json):
    python -I scripts/stress/stress_report.py --stats STATS.json --deletion DELETION.json --sha1sums SHA1SUMS.txt
Another corpus (docs/stress/<name>.md and <name>.json), one or more runs on one page:
    python -I scripts/stress/stress_report.py --corpus fleurs --title "FLEURS ar_eg transcripts" \
        --source-url URL --licence "CC BY 4.0" --retrieved 2026-10-15T10:46:00Z \
        --run "transcription column=PATH.json" --run "raw_transcription column=PATH.json"
"""
import argparse
import json
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "docs", "stress")
POLICIES = ["bayanat-norm-v1", "asr-eval-v1", "raw-safe-v1"]
LOSSY = ["alef_variants.map", "alef_maqsura.to_yeh", "taa_marbuta.to_heh"]
OTHER_CORPORA = [("fleurs", "FLEURS ar_eg transcripts (read-speech sentences)")]


def pct(a, b):
    return "%.2f%%" % (100.0 * a / b) if b else "n/a"


def per_k(a, b):
    return "%.3f" % (1000.0 * a / b) if b else "n/a"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stats")
    ap.add_argument("--deletion")
    ap.add_argument("--sha1sums")
    ap.add_argument("--corpus")
    ap.add_argument("--title")
    ap.add_argument("--source-url")
    ap.add_argument("--licence")
    ap.add_argument("--retrieved")
    ap.add_argument("--run", action="append", default=[], metavar="LABEL=PATH")
    a = ap.parse_args()
    if a.corpus:
        return corpus_report(a)
    d = json.load(open(a.stats, encoding="utf-8"))
    dele = json.load(open(a.deletion, encoding="utf-8"))
    fetch = dele["fetch"]
    dump_name = d["dump"]["file"]
    dated = None
    sha1_ok = None
    suffix = dump_name.split("arwiki-latest-", 1)[1]
    with open(a.sha1sums, encoding="utf-8") as f:
        for line in f:
            h, n = line.split()
            if re.fullmatch(r"arwiki-\d{8}-" + re.escape(suffix), n):
                dated, sha1_ok = n, (h == dele["sha1"])
    assert dated and sha1_ok, "dump sha1 not verified against the published sha1sums"
    os.makedirs(OUT, exist_ok=True)
    n_art, letters = d["articles"], d["arabic_letters"]

    L = []
    w = L.append
    w("# Stress run on Arabic Wikipedia (statistics only)")
    w("")
    w("Generated by `scripts/stress/stress_run.py` and `scripts/stress/stress_report.py` from one Arabic Wikipedia "
      "dump part. This page holds numbers only: no article text was stored, published or added to the package or "
      "the fixtures. Raw wikitext was used as it is in the dump (markup, templates and links included), which is a "
      "harder input than clean prose.")
    w("")
    others = [(n, t) for n, t in OTHER_CORPORA if os.path.exists(os.path.join(OUT, n + ".md"))]
    if others:
        w("Other corpora: %s." % "; ".join("[%s](%s.md)" % (t, n) for n, t in others))
        w("")
    w("## Input")
    w("")
    w("| Field | Value |")
    w("|---|---|")
    w("| Source | https://dumps.wikimedia.org/arwiki/latest/%s |" % dump_name)
    w("| Dated file name | %s |" % dated)
    w("| Retrieved | %s (single HTTPS download, Bayanat Labs User-Agent) |" % fetch["requested_at"])
    w("| Size | %d bytes (bzip2) |" % d["dump"]["bytes"])
    w("| SHA-256 | `%s` |" % d["dump"]["sha256"])
    w("| SHA-1 | `%s`, equal to the value in Wikimedia's published `arwiki-latest-sha1sums.txt` |" % dele["sha1"])
    w("| Licence of the text | Wikipedia text is CC BY-SA 4.0 (and GFDL); used here for internal statistics only, "
      "nothing redistributed |")
    w("| Deleted | %s; file absent afterwards: %s |" % (dele["deleted_at"], "yes" if dele["absent_after"] else "no"))
    w("| Pages read | %d (all namespaces) |" % d["pages_seen"])
    w("| Main-namespace redirects skipped | %d |" % d["main_namespace_redirects_skipped"])
    w("| Articles processed (main namespace, not redirects, non-empty) | %d |" % n_art)
    w("| Code points | %d |" % d["code_points"])
    w("| UTF-8 bytes | %d |" % d["utf8_bytes"])
    w("| Arabic letters (Lo, Script=Arabic, after presentation-form mapping) | %d |" % letters)
    w("| Library | arabic-normalize %s, UCD %s |" % (d["lib_version"], d["unicode_version"]))
    w("| Machine | Apple M3 Pro, 18 GB RAM, no GPU (%s), Python %s |" % (d["machine"]["platform"],
                                                                        d["machine"]["python"]))
    w("")
    w("Every article went through all three pilot policies, in plain mode (`normalize`) and detailed mode "
      "(`normalize_detailed`).")
    w("")
    w("## Robustness")
    w("")
    w("| Check | bayanat-norm-v1 | asr-eval-v1 | raw-safe-v1 |")
    w("|---|---|---|---|")

    def cnt(dct, p, key=None):
        if key is None:
            return dct.get(p, 0)
        return dct.get("%s:%s" % (p, key), 0)

    crashes = {p: sum(v for k, v in d["crashes"].items() if k.startswith(p + ":")) for p in POLICIES}
    w("| Crashes (exceptions) | %s |" % " | ".join(str(crashes[p]) for p in POLICIES))
    for key, label in [("offset_map_length", "Offset map length differs from output length"),
                       ("offset_span_out_of_range", "Offset span outside the input"),
                       ("offset_starts_not_monotone", "Offset starts decrease without canonical reordering"),
                       ("change_span_out_of_range", "Change-log span outside the input"),
                       ("silent_change_outside_change_log", "Input code point changed without a change-log entry"),
                       ("lossy_flags_mismatch", "lossy_flags differ from the lossy rules in the change log")]:
        w("| %s | %s |" % (label, " | ".join(str(cnt(d["consistency_failures"], p, key)) for p in POLICIES)))
    w("| Plain and detailed output differ | %s |" % " | ".join(str(cnt(d["plain_detailed_mismatch"], p))
                                                          for p in POLICIES))
    w("| Output not idempotent (normalising it again changes it) | %s |" % " | ".join(
        str(cnt(d["not_idempotent"], p)) for p in POLICIES))
    w("| Output not in NFC | %s |" % " | ".join(str(cnt(d["not_nfc"], p)) for p in POLICIES))
    total_cons = sum(d["consistency_failures"].values())
    w("")
    w("Total crashes: %d. Total offset-map and change-log consistency failures: %d." % (sum(crashes.values()),
                                                                                      total_cons))
    w("")
    w("## Throughput")
    w("")
    sc = d["single_core"]
    w("One process on one core, first %d articles (%d UTF-8 bytes), CPU time:" % (sc["articles"], sc["utf8_bytes"]))
    w("")
    w("| Policy | Plain MB/s | Detailed MB/s |")
    w("|---|---|---|")
    for p in POLICIES:
        r = sc["policies"][p]
        w("| %s | %.2f | %.2f |" % (p, r["plain_MBps"], r["detailed_MBps"]))
    w("")
    w("The pilot target is at least 5 MB/s per core for bayanat-norm-v1 in Python; plain mode measured "
      "%.2f MB/s and detailed mode %.2f MB/s." % (sc["policies"]["bayanat-norm-v1"]["plain_MBps"],
                                                  sc["policies"]["bayanat-norm-v1"]["detailed_MBps"]))
    w("")
    w("Full run: %d worker processes, %.1f s wall time for all articles, all three policies, both modes and all "
      "checks. Summed worker time per policy:" % (d["machine"]["workers"], d["wall_seconds_parallel"]))
    w("")
    w("| Policy | Plain s | Detailed s | Plain MB/s per worker | Detailed MB/s per worker |")
    w("|---|---|---|---|---|")
    for p in POLICIES:
        r = d["parallel_worker_seconds"][p]
        w("| %s | %.2f | %.2f | %.2f | %.2f |" % (p, r["plain"], r["detailed"], d["utf8_bytes"] / 1e6 / r["plain"],
                                               d["utf8_bytes"] / 1e6 / r["detailed"]))
    w("")
    w("Per-worker rates are lower than the single-core rates because the workers share performance and efficiency "
      "cores and run the consistency checks in between.")
    w("")
    w("## Lossy flags per policy")
    w("")
    w("| Policy | Articles with any lossy flag | Share of articles |")
    w("|---|---|---|")
    for p in POLICIES:
        k = d["articles_with_any_lossy"].get(p, 0)
        w("| %s | %d | %s |" % (p, k, pct(k, n_art)))
    w("")
    w("| Policy | Lossy rule | Changes | Per 1,000 Arabic letters | Articles with the rule | Share of articles |")
    w("|---|---|---|---|---|---|")
    for p in POLICIES:
        for r in LOSSY:
            c = d["rules"][p].get(r, 0)
            aw = d["articles_with_rule"][p].get(r, 0)
            w("| %s | %s | %d | %s | %d | %s |" % (p, r, c, per_k(c, letters), aw, pct(aw, n_art)))
    w("")
    w("bayanat-norm-v1 keeps ة (taa_marbuta: flag) and raw-safe-v1 has no lossy rule, so their zero rows "
      "confirm that those rules never fired.")
    w("")
    w("## Informational flags and rejected code points")
    w("")
    w("| Policy | Flag | Articles | Share |")
    w("|---|---|---|---|")
    for p in POLICIES:
        for fl, k in sorted(d["flags"][p].items()):
            w("| %s | %s | %d | %s |" % (p, fl, k, pct(k, n_art)))
    w("")
    rej = d["rejected_spans_by_reason"]
    w("Rejected spans (removed and reported by every policy), by reason: %s." % (
        ", ".join("%s %d" % kv for kv in sorted(rej.items())) or "none"))
    w("")
    w("## All rules, per policy")
    w("")
    w("| Policy | Rule | Changes | Per 1,000 Arabic letters | Articles | Share of articles |")
    w("|---|---|---|---|---|---|")
    for p in POLICIES:
        for r, c in d["rules"][p].items():
            aw = d["articles_with_rule"][p].get(r, 0)
            w("| %s | %s | %d | %s | %d | %s |" % (p, r, c, per_k(c, letters), aw, pct(aw, n_art)))
    w("")
    w("Change counts follow the change log: one entry per changed code point, per changed normalisation chunk, or "
      "per changed whitespace run (SPEC section 4).")
    w("")
    w("## Lossy changes by context class")
    w("")
    w("Each lossy change of bayanat-norm-v1 (alef variants, alef maqsura) and each taa-marbuta change of "
      "asr-eval-v1 is classed by the source code point and its position in the Arabic word (marks, tatweel and "
      "ZWNJ skipped). `stem_initial_after_prefix` means the letter follows only a common proclitic such as ال، "
      "و، ف، ب، ك، ل or لل. These classes are reviewed in [../LOSSY_REVIEW.md](../LOSSY_REVIEW.md).")
    w("")
    w("| Rule | Source | Position | Extra context | Changes | Share of the rule's changes |")
    w("|---|---|---|---|---|---|")
    by_rule = {}
    for k, c in d["lossy_classes"].items():
        by_rule[k.split("|")[0]] = by_rule.get(k.split("|")[0], 0) + c
    for k, c in d["lossy_classes"].items():
        parts = k.split("|")
        w("| %s | %s | %s | %s | %d | %s |" % (parts[0], parts[1], parts[2], ", ".join(parts[3:]) or "",
                                               c, pct(c, by_rule[parts[0]])))
    w("")
    w("## Distinct word types merged by the lossy rules")
    w("")
    w("Arabic-letter tokens were taken from the raw-safe-v1 output. Each token's base form removes only "
      "non-lossy differences (harakat, tatweel, Quranic marks, superscript alef, presentation forms, invisible "
      "controls). A base form counts as merged when the policy maps it to the same output as a different base "
      "form (for example على and علي under bayanat-norm-v1).")
    w("")
    w("| Policy | Distinct base forms | Merged with another | Share | Tokens | Tokens of merged forms | Share |")
    w("|---|---|---|---|---|---|---|")
    for p, m in d["word_type_merges"].items():
        w("| %s | %d | %d | %s | %d | %d | %s |" % (p, m["distinct_base_types"], m["base_types_merged_with_another"],
                                                  pct(m["base_types_merged_with_another"], m["distinct_base_types"]),
                                                  m["tokens"], m["tokens_of_merged_types"],
                                                  pct(m["tokens_of_merged_types"], m["tokens"])))
    w("")
    w("A merge is not always an error: it also joins spelling variants of one word (for example a name written "
      "with and without hamza). The shares bound how much of this corpus's vocabulary a lossy rule can confuse.")
    w("")
    with open(os.path.join(OUT, "report.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    keep = {k: v for k, v in d.items() if k != "crash_article_indices"}
    keep["dump"]["sha1"] = dele["sha1"]
    keep["dump"]["dated_name"] = dated
    keep["dump"]["deleted_at"] = dele["deleted_at"]
    keep["dump"]["retrieved_at"] = fetch["requested_at"]
    with open(os.path.join(OUT, "stats.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(keep, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print("wrote", os.path.join(OUT, "report.md"))


RENAME = {"articles": "texts", "articles_with_rule": "texts_with_rule",
          "articles_with_any_lossy": "texts_with_any_lossy"}


def corpus_report(a):
    runs = []
    for item in a.run:
        label, _, path = item.partition("=")
        d = json.load(open(path, encoding="utf-8"))
        assert "source" in d, "not a text-corpus run: %s" % path
        runs.append((label, d))
    unit = runs[0][1]["source"]["unit"]
    units = unit + "s"
    L = []
    w = L.append
    w("# Stress run on %s (statistics only)" % a.title)
    w("")
    w("Generated by `scripts/stress/stress_run.py` and `scripts/stress/stress_report.py`. This page holds numbers "
      "only: no %s text is stored in this repository, the package or the fixtures. The Wikipedia run, with "
      "throughput, is in [report.md](report.md)." % unit)
    w("")
    w("## Input")
    w("")
    w("| Field | Value |")
    w("|---|---|")
    w("| Source | %s |" % a.source_url)
    w("| Retrieved | %s (Bayanat Labs User-Agent) |" % a.retrieved)
    w("| Licence of the text | %s; used here for internal statistics only, nothing redistributed |" % a.licence)
    files = runs[0][1]["source"]["files"]
    for f in files:
        w("| File | %s, %d bytes, SHA-256 `%s` |" % (f["file"], f["bytes"], f["sha256"]))
    w("| Library | arabic-normalize %s, UCD %s |" % (runs[0][1]["lib_version"], runs[0][1]["unicode_version"]))
    w("")
    w("| Run | %s available | Requested sample (seed) | %s processed | Code points | Arabic letters |"
      % (units.capitalize(), units.capitalize()))
    w("|---|---|---|---|---|---|")
    for label, d in runs:
        src = d["source"]
        w("| %s | %d | %s | %d | %d | %d |" % (label, src["texts_available"],
                                            "%d (%d)" % (src["sample_requested"], src["seed"])
                                            if src["sample_requested"] else "all",
                                            d["articles"], d["code_points"], d["arabic_letters"]))
    w("")
    short = [label for label, d in runs if d["source"]["sample_requested"]
             and d["source"]["texts_available"] < d["source"]["sample_requested"]]
    if short:
        w("The corpus has fewer distinct %s than the requested sample, so all of them were used (%s)."
          % (units, ", ".join(short)))
        w("")
    w("Every %s went through all three pilot policies, in plain and detailed mode." % unit)
    w("")
    w("## Robustness")
    w("")
    w("| Run | Policy | Crashes | Consistency failures | Plain and detailed differ | Not idempotent | Not NFC |")
    w("|---|---|---|---|---|---|---|")
    for label, d in runs:
        for p in POLICIES:
            crashes = sum(v for k, v in d["crashes"].items() if k.startswith(p + ":"))
            cons = sum(v for k, v in d["consistency_failures"].items() if k.startswith(p + ":"))
            w("| %s | %s | %d | %d | %d | %d | %d |" % (label, p, crashes, cons, d["plain_detailed_mismatch"].get(p, 0),
                                                     d["not_idempotent"].get(p, 0), d["not_nfc"].get(p, 0)))
    w("")
    w("## Lossy flags")
    w("")
    w("| Run | Policy | %s with any lossy flag | Share |" % units.capitalize())
    w("|---|---|---|---|")
    for label, d in runs:
        for p in POLICIES:
            k = d["articles_with_any_lossy"].get(p, 0)
            w("| %s | %s | %d | %s |" % (label, p, k, pct(k, d["articles"])))
    w("")
    w("| Run | Policy | Lossy rule | Changes | Per 1,000 Arabic letters | %s with the rule | Share |"
      % units.capitalize())
    w("|---|---|---|---|---|---|---|")
    for label, d in runs:
        for p in POLICIES[:2]:
            for r in LOSSY:
                c = d["rules"][p].get(r, 0)
                aw = d["articles_with_rule"][p].get(r, 0)
                w("| %s | %s | %s | %d | %s | %d | %s |" % (label, p, r, c, per_k(c, d["arabic_letters"]), aw,
                                                         pct(aw, d["articles"])))
    w("")
    w("## All rules and flags")
    w("")
    w("| Run | Policy | Rule or flag | Changes (rules) | %s | Share |" % units.capitalize())
    w("|---|---|---|---|---|---|")
    for label, d in runs:
        for p in POLICIES:
            for r, c in d["rules"][p].items():
                aw = d["articles_with_rule"][p].get(r, 0)
                w("| %s | %s | %s | %d | %d | %s |" % (label, p, r, c, aw, pct(aw, d["articles"])))
            for fl, k in sorted(d["flags"][p].items()):
                w("| %s | %s | %s (flag) | | %d | %s |" % (label, p, fl, k, pct(k, d["articles"])))
    rej = {label: d["rejected_spans_by_reason"] for label, d in runs}
    w("")
    w("Rejected spans by reason: %s." % "; ".join("%s: %s" % (label, ", ".join("%s %d" % kv for kv in sorted(r.items()))
                                                                    or "none") for label, r in rej.items()))
    w("")
    w("## Lossy changes by context class")
    w("")
    w("Classes as in [report.md](report.md) (source code point and position in the Arabic word).")
    w("")
    w("| Run | Rule | Source | Position | Extra context | Changes | Share of the rule's changes |")
    w("|---|---|---|---|---|---|---|")
    for label, d in runs:
        by_rule = {}
        for k, c in d["lossy_classes"].items():
            by_rule[k.split("|")[0]] = by_rule.get(k.split("|")[0], 0) + c
        for k, c in d["lossy_classes"].items():
            parts = k.split("|")
            w("| %s | %s | %s | %s | %s | %d | %s |" % (label, parts[0], parts[1], parts[2], ", ".join(parts[3:]),
                                                     c, pct(c, by_rule[parts[0]])))
    w("")
    w("## Distinct word types merged by the lossy rules")
    w("")
    w("| Run | Policy | Distinct base forms | Merged with another | Share | Tokens | Tokens of merged forms | Share |")
    w("|---|---|---|---|---|---|---|---|")
    for label, d in runs:
        for p, m in d["word_type_merges"].items():
            w("| %s | %s | %d | %d | %s | %d | %d | %s |" % (
                label, p, m["distinct_base_types"], m["base_types_merged_with_another"],
                pct(m["base_types_merged_with_another"], m["distinct_base_types"]), m["tokens"],
                m["tokens_of_merged_types"], pct(m["tokens_of_merged_types"], m["tokens"])))
    w("")
    w("Throughput is not reported for this corpus: the texts are short and the run takes well under a second, so "
      "timings would mostly measure fixed overhead.")
    w("")
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, a.corpus + ".md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    keep = {"corpus": a.title, "source_url": a.source_url, "licence": a.licence, "retrieved_at": a.retrieved,
            "runs": []}
    for label, d in runs:
        r = {RENAME.get(k, k): v for k, v in d.items()
             if k not in ("crash_article_indices", "single_core", "parallel_worker_seconds", "wall_seconds_parallel",
                          "elapsed_total_seconds", "pages_seen", "main_namespace_redirects_skipped")}
        keep["runs"].append({"label": label, **r})
    with open(os.path.join(OUT, a.corpus + ".json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(keep, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print("wrote", os.path.join(OUT, a.corpus + ".md"))
    return 0


if __name__ == "__main__":
    main()
