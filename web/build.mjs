writeFileSync(join(SPACE, 'README.md'), readme);

// Manifest of every file in the Space.
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    const rel = relative(SPACE, p);
    if (rel === 'MANIFEST.json' || rel.startsWith('.git') || name === '.DS_Store') continue;
    if (statSync(p).isDirectory()) walk(p);
    else {
      const b = readFileSync(p);
      files.push({ path: rel, bytes: b.length, sha256: createHash('sha256').update(b).digest('hex') });
    }
  }
}(SPACE));
const pkg = JSON.parse(readFileSync(join(REPO, 'js', 'package.json'), 'utf8'));
writeFileSync(join(SPACE, 'MANIFEST.json'), `${JSON.stringify({
  space: 'Bayanat-Labs/arabic-normalizer',
  library: `${pkg.name} ${pkg.version}`,
  files,
}, null, 1)}\n`);
console.log(`space assembled: ${files.length} files`);
