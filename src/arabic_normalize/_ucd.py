BIDI_CONTROLS = _expand(_T["bidi_control"])
SCRIPT_ARABIC = _expand(_T["script_arabic"])
SCRIPT_LATIN = _expand(_T["script_latin"])
ARABIC_LETTERS = frozenset(LETTER_LO & SCRIPT_ARABIC)
EXT_PICT = _expand(_T["extended_pictographic"])
EMOJI_MODIFIER = _expand(_T["emoji_modifier"])
JOINING = {}
for _t, _ranges in _T["joining_type"].items():
    for _lo, _hi in _ranges:
        for _c in range(_lo, _hi + 1):
            JOINING[_c] = _t
LATIN_LOWER = {c: low for c, low in _T["latin_lower"]}
