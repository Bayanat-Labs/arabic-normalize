COMPAT_DECOMPOSABLE = frozenset(_T["compat_decomposable"])


def joining_type(cp: int) -> str:
    return JOINING.get(cp, "U")


def name(cp: int) -> str:
    n = NAMES.get(cp)
    if n:
        return n
    return "U+%04X (%s)" % (cp, general_category(cp))


# --- Normalisation data ----------------------------------------------------------------------------
CCC = {c: v for c, v in _T["ccc"]}
_NFD = {r[0]: tuple(r[1:]) for r in _T["nfd"]}
_NFKD = {r[0]: tuple(r[1:]) for r in _T["nfkd"]}
_COMPOSE = {(a, b): c for a, b, c in _T["compose"]}
_QC_NOT_YES = {
    "NFC": _expand(_T["nfc_qc_no"]) | _expand(_T["nfc_qc_maybe"]),
    "NFKC": _expand(_T["nfkc_qc_no"]) | _expand(_T["nfkc_qc_maybe"]),
}
_QC_NO_DECOMP = {  # for the D forms: a code point is stable if it does not decompose and has ccc 0
    "NFD": frozenset(_NFD),
    "NFKD": frozenset(_NFKD),
}

S_BASE, L_BASE, V_BASE, T_BASE = 0xAC00, 0x1100, 0x1161, 0x11A7
L_COUNT, V_COUNT, T_COUNT = 19, 21, 28
N_COUNT = V_COUNT * T_COUNT
S_COUNT = L_COUNT * N_COUNT


def _decompose_cp(cp, compat):
    if S_BASE <= cp < S_BASE + S_COUNT:
        s = cp - S_BASE
        lv = (L_BASE + s // N_COUNT, V_BASE + (s % N_COUNT) // T_COUNT)
        t = s % T_COUNT
        return lv + ((T_BASE + t,) if t else ())
    m = _NFKD if compat else _NFD
    return m.get(cp)


def _compose_pair(a, b):
    if L_BASE <= a < L_BASE + L_COUNT and V_BASE <= b < V_BASE + V_COUNT:
        return S_BASE + ((a - L_BASE) * V_COUNT + (b - V_BASE)) * T_COUNT
    if S_BASE <= a < S_BASE + S_COUNT and (a - S_BASE) % T_COUNT == 0 and T_BASE < b < T_BASE + T_COUNT:
        return a + (b - T_BASE)
    return _COMPOSE.get((a, b))


def _normalize_items(items, form):
    """items: list of (cp, lo, hi) with source span [lo, hi). Returns the normalised list of (cp, lo, hi)."""
    compat = form in ("NFKC", "NFKD")
    dec = []
    for cp, lo, hi in items:
        d = _decompose_cp(cp, compat)
        if d is None:
            dec.append([cp, lo, hi])
        else:
            for x in d:
                dec.append([x, lo, hi])
    # Canonical ordering: stable sort of each run of non-starters by combining class.
    i, n = 0, len(dec)
    while i < n:
        if CCC.get(dec[i][0], 0) == 0:
            i += 1
            continue
        j = i
        while j < n and CCC.get(dec[j][0], 0) != 0:
            j += 1
        if j - i > 1:
            dec[i:j] = sorted(dec[i:j], key=lambda e: CCC[e[0]])
        i = j
    if form in ("NFD", "NFKD") or not dec:
        return [tuple(e) for e in dec]
    # Canonical composition (UAX #15 reference algorithm).
    out = [dec[0]]
    starter = 0
    last_class = CCC.get(dec[0][0], 0)
    if last_class != 0:
        last_class = 256
    for cp, lo, hi in dec[1:]:
        cls = CCC.get(cp, 0)
        comp = _compose_pair(out[starter][0], cp)
        if comp is not None and (last_class < cls or last_class == 0):
            s = out[starter]
            out[starter] = [comp, min(s[1], lo), max(s[2], hi)]
            continue
        if cls == 0:
            starter = len(out)
        last_class = cls
        out.append([cp, lo, hi])
    return [tuple(e) for e in out]


class _FormData(object):
    __slots__ = ("form", "unstable_re", "unstable")

    def __init__(self, form):
        self.form = form
        if form in ("NFC", "NFKC"):
            unstable = set(_QC_NOT_YES[form]) | set(CCC)
        else:
            unstable = set(_QC_NO_DECOMP[form]) | set(CCC) | set(range(S_BASE, S_BASE + S_COUNT))
        self.unstable = frozenset(unstable)
        self.unstable_re = CharMatcher(unstable)


_FORMS = {}


def _form(form):
    fd = _FORMS.get(form)
    if fd is None:
        fd = _FORMS[form] = _FormData(form)
    return fd


def normalization_edits(s: str, form: str):
    """Return a list of edits (start, end, replacement, sub_spans) that bring ``s`` to ``form``.

    ``sub_spans`` gives, for each code point of ``replacement``, the local span [lo, hi) in ``s`` it came from.
    Chunks start at a stable code point (combining class 0 and Quick_Check=Yes), so chunks are independent.
    """
    fd = _form(form)
    unstable = fd.unstable
    edits = []
    n = len(s)
    last_end = -1
    for m in fd.unstable_re.finditer(s):
        k = m.start()
        if k < last_end:
            continue
        a = k
        while a > 0 and ord(s[a]) in unstable:
            a -= 1
        b = k + 1
        while b < n and ord(s[b]) in unstable:
            b += 1
        if a < last_end:  # cannot happen (chunks are maximal), kept as a guard
            a = last_end
        last_end = b
        chunk = s[a:b]
        if _quick_yes(chunk, form):
            continue
        items = [(ord(c), a + i, a + i + 1) for i, c in enumerate(chunk)]
        res = _normalize_items(items, form)
        rep = "".join(chr(cp) for cp, _, _ in res)
        if rep != chunk:
            edits.append((a, b, rep, [(lo, hi) for _, lo, hi in res]))
    return edits


def _quick_yes(chunk, form):
    """True when the chunk is certainly already in ``form`` (Quick_Check=Yes and marks in canonical order)."""
    if form not in ("NFC", "NFKC"):
        return False
    qc = _QC_NOT_YES[form]
    last = 0
    for c in chunk:
        cp = ord(c)
        if cp in qc:
            return False
        cls = CCC.get(cp, 0)
        if cls != 0 and last > cls:
            return False
        last = cls
    return True


def normalize_form(s: str, form: str) -> str:
    """Plain NFC, NFD, NFKC or NFKD of ``s`` using the pinned tables."""
    edits = normalization_edits(s, form)
    if not edits:
        return s
    out = []
    pos = 0
    for a, b, rep, _ in edits:
        out.append(s[pos:a])
        out.append(rep)
        pos = b
    out.append(s[pos:])
    return "".join(out)
