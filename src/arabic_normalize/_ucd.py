"""Pinned Unicode data (UCD 18.0.0) and a span-tracking implementation of UAX #15 normalisation.

Nothing here uses the interpreter's ``unicodedata`` module, so results do not depend on the Python version.
The tables in ``tables/ucd_tables.json`` are generated by ``scripts/build_tables.py`` from the pinned UCD.
"""
from __future__ import annotations

import bisect
import json
import os
import re

_TABLE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables", "ucd_tables.json")

with open(_TABLE_PATH, encoding="utf-8") as _f:
    _T = json.load(_f)

UNICODE_VERSION = _T["unicode_version"]


def _expand(ranges):
    out = set()
    for lo, hi in ranges:
        out.update(range(lo, hi + 1))
    return frozenset(out)


def char_class(cps):
    """Regex character class (string) matching exactly the given code points."""
    cps = sorted(set(cps))
    parts = []
    i = 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1:
            j += 1
        lo, hi = cps[i], cps[j]
        if lo == hi:
            parts.append(_esc(lo))
        elif hi == lo + 1:
            parts.append(_esc(lo) + _esc(hi))
        else:
            parts.append(_esc(lo) + "-" + _esc(hi))
        i = j + 1
    return "[" + "".join(parts) + "]"


def _esc(cp):
    return "\\U%08x" % cp if cp > 0xFFFF else "\\u%04x" % cp


_ASTRAL = re.compile("[\\U00010000-\\U0010ffff]")


class CharMatcher(object):
    """Fast regex search over a code-point set.

    Python's re engine tests large astral ranges slowly, so the set is split: a BMP class (fast table lookup) is
    used alone when the text has no astral code point, and a combined pattern otherwise.
    """

    __slots__ = ("bmp", "full", "has_astral")

    def __init__(self, cps):
        cps = sorted(set(cps))
        bmp = [c for c in cps if c < 0x10000]
        ast = [c for c in cps if c >= 0x10000]
        self.has_astral = bool(ast)
        self.bmp = re.compile(char_class(bmp)) if bmp else None
        if bmp and ast:
            self.full = re.compile("(?:%s|(?=[\\U00010000-\\U0010ffff])%s)" % (char_class(bmp), char_class(ast)))
        elif ast:
            self.full = re.compile(char_class(ast))
        else:
            self.full = self.bmp

    def _pick(self, s):
        if self.has_astral and _ASTRAL.search(s) is not None:
            return self.full
        return self.bmp

    def search(self, s):
        r = self._pick(s)
        return r.search(s) if r is not None else None

    def finditer(self, s):
        r = self._pick(s)
        return r.finditer(s) if r is not None else iter(())

    def match(self, s):
        return self.full.match(s) if self.full is not None else None


# --- General category (bisect over ranges) -------------------------------------------------------------
_GC_STARTS = [r[0] for r in _T["gc_ranges"]]
_GC_RANGES = _T["gc_ranges"]


def general_category(cp: int) -> str:
    i = bisect.bisect_right(_GC_STARTS, cp) - 1
    if i >= 0:
        lo, hi, cat = _GC_RANGES[i]
        if lo <= cp <= hi:
            return cat
    return "Cn"


def _gc_set(prefixes):
    out = set()
    for lo, hi, cat in _GC_RANGES:
        if cat.startswith(prefixes):
            out.update(range(lo, hi + 1))
    return frozenset(out)


MARKS = _gc_set(("Mn", "Mc", "Me"))
CONTROLS = _gc_set(("Cc",))
PUNCTUATION = _gc_set(("P",))
LETTER_LO = _gc_set(("Lo",))
WHITE_SPACE = _expand(_T["white_space"])
